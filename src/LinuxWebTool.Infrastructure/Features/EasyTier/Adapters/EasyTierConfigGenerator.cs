using System.Text;
using System.Text.Json;
namespace LinuxWebTool.Infrastructure.Features.EasyTier.Adapters;

/// <summary>
/// EasyTier 节点 TOML 配置生成与校验器
/// </summary>
public static class EasyTierConfigGenerator
{
    public static string GenerateToml(EasyTierNodeEntity entity)
    {
        if (!string.IsNullOrWhiteSpace(entity.RawTomlOverride))
        {
            return entity.RawTomlOverride.Trim();
        }

        var sb = new StringBuilder();
        sb.AppendLine($"# Generated by LinuxWebTool EasyTier Manager at {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine($"inst_name = \"{EscapeTomlString(entity.InstanceName)}\"");
        sb.AppendLine($"network_name = \"{EscapeTomlString(entity.NetworkName)}\"");

        if (!string.IsNullOrWhiteSpace(entity.NetworkSecret))
        {
            sb.AppendLine($"network_secret = \"{EscapeTomlString(entity.NetworkSecret)}\"");
        }

        if (!string.IsNullOrWhiteSpace(entity.VirtualIpv4))
        {
            sb.AppendLine($"ipv4 = \"{EscapeTomlString(entity.VirtualIpv4)}\"");
        }

        sb.AppendLine($"dhcp = {(entity.EnableDhcp ? "true" : "false")}");

        // 兼容 CoreBinary [network_identity] 表与 FFI 顶层字段
        sb.AppendLine("[network_identity]");
        sb.AppendLine($"network_name = \"{EscapeTomlString(entity.NetworkName)}\"");
        sb.AppendLine($"network_secret = \"{EscapeTomlString(entity.NetworkSecret ?? "")}\"");
        sb.AppendLine();

        // Listeners
        var listeners = DeserializeList(entity.ListenersJson);
        if (listeners.Count > 0)
        {
            var normalized = NormalizeListeners(listeners);
            sb.AppendLine($"listeners = [{string.Join(", ", normalized.Select(l => $"\"{EscapeTomlString(l)}\""))}]");
        }
        else
        {
            sb.AppendLine("no_listener = true");
        }

        // Peers (同时支持 [[peer]] 表数组与 peers 列表)
        var peers = DeserializeList(entity.PeersJson);
        if (peers.Count > 0)
        {
            sb.AppendLine($"peers = [{string.Join(", ", peers.Select(p => $"\"{EscapeTomlString(p)}\""))}]");
            foreach (var p in peers)
            {
                sb.AppendLine();
                sb.AppendLine("[[peer]]");
                sb.AppendLine($"uri = \"{EscapeTomlString(p)}\"");
            }
        }

        // Proxy networks
        var proxyNetworks = DeserializeList(entity.ProxyNetworksJson);
        if (proxyNetworks.Count > 0)
        {
            sb.AppendLine($"proxy_networks = [{string.Join(", ", proxyNetworks.Select(pn => $"\"{EscapeTomlString(pn)}\""))}]");
            foreach (var pn in proxyNetworks)
            {
                sb.AppendLine();
                sb.AppendLine("[[proxy_network]]");
                sb.AppendLine($"cidr = \"{EscapeTomlString(pn)}\"");
            }
        }

        // Routes
        var routes = DeserializeList(entity.RoutesJson);
        if (routes.Count > 0)
        {
            sb.AppendLine($"routes = [{string.Join(", ", routes.Select(r => $"\"{EscapeTomlString(r)}\""))}]");
        }

        return sb.ToString();
    }

