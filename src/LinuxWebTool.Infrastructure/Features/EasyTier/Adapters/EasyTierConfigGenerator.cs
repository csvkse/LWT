    public static bool ValidateConfig(string toml, out string? error)
    {
        if (string.IsNullOrWhiteSpace(toml))
        {
            error = "配置内容不能为空";
            return false;
        }

        if (EasyTierNativeMethods.ProbeLibrary(out _))
        {
            try
            {
                var ret = EasyTierNativeMethods.parse_config(toml);
                if (ret != 0)
                {
                    error = EasyTierNativeMethods.GetLastErrorMessage();
                    return false;
                }
                error = null;
                return true;
            }
            catch (Exception ex)
            {
                error = $"调用 parse_config 发生异常: {ex.Message}";
                return false;
            }
        }

        // 基础语法结构启发式校验
        if (!toml.Contains("inst_name"))
        {
            error = "缺少必需的 inst_name 字段";
            return false;
        }

        error = null;
        return true;
    }

    private static List<string> DeserializeList(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return [];
        try
        {
            return JsonSerializer.Deserialize(json, EasyTierJsonContext.Default.ListString) ?? [];
        }
        catch
        {
            return [];
        }
    }

    private static List<string> NormalizeListeners(List<string> listeners)
    {
        var result = new List<string>();
        foreach (var item in listeners)
        {
            var trimmed = item.Trim();
            if (string.IsNullOrEmpty(trimmed)) continue;

            // 纯端口号（例如 "11010"）自动补充 tcp、udp、wg 的 IPv4 与 IPv6 全套监听
            if (int.TryParse(trimmed, out var port) && port > 0 && port <= 65535)
            {
                result.Add($"tcp://0.0.0.0:{port}");
                result.Add($"udp://0.0.0.0:{port}");
                result.Add($"wg://0.0.0.0:{port + 1}");
                result.Add($"tcp://[::]:{port}");
                result.Add($"udp://[::]:{port}");
                result.Add($"wg://[::]:{port + 1}");
            }
            // 缺少 scheme 的 host:port（例如 "0.0.0.0:11010" 或 ":11010"）
            else if (trimmed.Contains(':') && !trimmed.Contains("://"))
            {
                var hostPort = trimmed.TrimStart(':');
                if (!hostPort.Contains(':')) hostPort = $"0.0.0.0:{hostPort}";
                result.Add($"tcp://{hostPort}");
                result.Add($"udp://{hostPort}");
            }
            // wg:// 前缀处理（默认端口 11011）
            else if (trimmed.StartsWith("wg://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[5..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("wg://0.0.0.0:11011");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("wg://[::]:11011");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"wg://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11011");
                else result.Add(trimmed);
            }
            // udp:// 前缀处理（默认端口 11010）
            else if (trimmed.StartsWith("udp://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[6..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("udp://0.0.0.0:11010");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("udp://[::]:11010");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"udp://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11010");
                else result.Add(trimmed);
            }
            // tcp:// 前缀处理（默认端口 11010）
            else if (trimmed.StartsWith("tcp://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[6..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("tcp://0.0.0.0:11010");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("tcp://[::]:11010");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"tcp://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11010");
                else result.Add(trimmed);
            }
            else
            {
                result.Add(trimmed);
            }
        }
        return result;
    }

    private static string EscapeTomlString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}
