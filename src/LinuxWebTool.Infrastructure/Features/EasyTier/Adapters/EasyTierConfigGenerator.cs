/// <summary>
/// EasyTier 节点 TOML 配置生成与校验器
/// </summary>
public static class EasyTierConfigGenerator
{
    public static string GenerateToml(EasyTierNodeEntity entity)
    {
        if (!string.IsNullOrWhiteSpace(entity.RawTomlOverride))
        {
            return entity.RawTomlOverride.Trim();
        }

        var listeners = DeserializeList(entity.ListenersJson);
        var mappedListeners = DeserializeList(entity.MappedListenersJson);
        var peers = DeserializeList(entity.PeersJson);
        var routes = DeserializeList(entity.RoutesJson);
        var proxyRules = DeserializeProxyRules(entity.ProxyNetworkRulesJson, entity.ProxyNetworksJson);
        var advancedConfig = DeserializeAdvancedConfig(entity.AdvancedConfigJson);

        return BuildToml(
            instanceName: entity.InstanceName,
            networkName: entity.NetworkName,
            networkSecret: entity.NetworkSecret,
            hostname: entity.Hostname,
            virtualIpv4: entity.VirtualIpv4,
            virtualIpv6: entity.VirtualIpv6,
            enableDhcp: entity.EnableDhcp,
            listeners: listeners,
            mappedListeners: mappedListeners,
            routingMode: entity.RoutingMode,
            routes: routes,
            peers: peers,
            proxyRules: proxyRules,
            advancedConfig: advancedConfig);
    }

    public static string GenerateToml(CreateEasyTierNodeRequest request)
    {
        if (!string.IsNullOrWhiteSpace(request.RawTomlOverride))
        {
            return request.RawTomlOverride.Trim();
        }

        var listeners = request.Listeners ?? [];
        var mappedListeners = request.MappedListeners ?? [];
        var peers = request.Peers ?? [];
        var routes = request.Routes ?? [];
        var proxyRules = ResolveProxyRules(request.ProxyNetworkRules, request.ProxyNetworks);

        return BuildToml(
            instanceName: request.InstanceName,
            networkName: request.NetworkName,
            networkSecret: request.NetworkSecret,
            hostname: request.Hostname,
            virtualIpv4: request.VirtualIpv4,
            virtualIpv6: request.VirtualIpv6,
            enableDhcp: request.EnableDhcp,
            listeners: listeners,
            mappedListeners: mappedListeners,
            routingMode: request.RoutingMode,
            routes: routes,
            peers: peers,
            proxyRules: proxyRules,
            advancedConfig: request.AdvancedConfig);
    }

    public static string BuildToml(
        string instanceName,
        string networkName,
        string? networkSecret,
        string? hostname,
        string? virtualIpv4,
        string? virtualIpv6,
        bool enableDhcp,
        List<string> listeners,
        List<string> mappedListeners,
        string? routingMode,
        List<string> routes,
        List<string> peers,
        List<EasyTierProxyNetworkItem> proxyRules,
        EasyTierAdvancedConfig? advancedConfig)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# Generated by LinuxWebTool EasyTier Manager at {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");

        // 1. 顶层必需配置与身份（必须在所有 [table] 之前输出）
        sb.AppendLine($"inst_name = \"{EscapeTomlString(instanceName)}\"");
        sb.AppendLine($"instance_name = \"{EscapeTomlString(instanceName)}\"");
        sb.AppendLine($"network_name = \"{EscapeTomlString(networkName)}\"");

        if (!string.IsNullOrWhiteSpace(networkSecret))
        {
            sb.AppendLine($"network_secret = \"{EscapeTomlString(networkSecret)}\"");
        }

        if (!string.IsNullOrWhiteSpace(hostname))
        {
            sb.AppendLine($"hostname = \"{EscapeTomlString(hostname)}\"");
        }

        if (!string.IsNullOrWhiteSpace(virtualIpv4))
        {
            sb.AppendLine($"ipv4 = \"{EscapeTomlString(virtualIpv4)}\"");
        }

        if (!string.IsNullOrWhiteSpace(virtualIpv6))
        {
            sb.AppendLine($"ipv6 = \"{EscapeTomlString(virtualIpv6)}\"");
        }

        // 表单中的地址代表静态配置，不能再让 DHCP 根据对端网段重新选址。
        sb.AppendLine($"dhcp = {(enableDhcp && string.IsNullOrWhiteSpace(virtualIpv4) ? "true" : "false")}");

        // 顶层 Listeners
        if (listeners.Count > 0)
        {
            var normalized = NormalizeListeners(listeners);
            sb.AppendLine($"listeners = [{string.Join(", ", normalized.Select(l => $"\"{EscapeTomlString(l)}\""))}]");
        }
        else
        {
            sb.AppendLine("no_listener = true");
        }

        // 顶层 Mapped Listeners (NAT 对外声明地址)
        if (mappedListeners.Count > 0)
        {
            sb.AppendLine($"mapped_listeners = [{string.Join(", ", mappedListeners.Select(ml => $"\"{EscapeTomlString(ml)}\""))}]");
        }

        // 顶层 Routes 路由模式控制：
        // 1. virtual_only: 显式输出 routes = []，阻断远端子网接管本地流量，仅保留虚拟 IP 互通
        // 2. manual: 输出指定的静态路由 routes = ["..."]（若空则输出 routes = []）
        // 3. auto (默认): 缺省省略 routes 字段，由 EasyTier 自动向对端学习代理路由
        // 兼容旧数据：若 routingMode 未指定或为空，旧数据有 routes 则输出，无则缺省省略
        var mode = routingMode?.Trim().ToLowerInvariant() ?? "";
        if (mode == "virtual_only")
        {
            sb.AppendLine("routes = []");
        }
        else if (mode == "manual")
        {
            sb.AppendLine($"routes = [{string.Join(", ", routes.Select(r => $"\"{EscapeTomlString(r)}\""))}]");
        }
        else if (mode == "auto")
        {
            // 自动学习模式：省略顶层 routes 字段
        }
        else
        {
            if (routes.Count > 0)
            {
                sb.AppendLine($"routes = [{string.Join(", ", routes.Select(r => $"\"{EscapeTomlString(r)}\""))}]");
            }
        }

        // 顶层 Peers 列表
        if (peers.Count > 0)
        {
            sb.AppendLine($"peers = [{string.Join(", ", peers.Select(p => $"\"{EscapeTomlString(p)}\""))}]");
        }

        // 顶层 Proxy Networks (简单网段列表，向后兼容)
        var simpleProxyCidrs = proxyRules.Where(r => string.IsNullOrWhiteSpace(r.MappedCidr)).Select(r => r.Cidr).ToList();
        if (simpleProxyCidrs.Count > 0)
        {
            sb.AppendLine($"proxy_networks = [{string.Join(", ", simpleProxyCidrs.Select(pn => $"\"{EscapeTomlString(pn)}\""))}]");
        }

        sb.AppendLine();

        // 2. 子表：[network_identity] (兼容 CoreBinary [network_identity] 表与 FFI 顶层字段)
        sb.AppendLine("[network_identity]");
        sb.AppendLine($"network_name = \"{EscapeTomlString(networkName)}\"");
        sb.AppendLine($"network_secret = \"{EscapeTomlString(networkSecret ?? "")}\"");
        sb.AppendLine();

        // 3. 子表：[flags] 高级连接与协议微调
        if (advancedConfig != null)
        {
            var flagsSb = new StringBuilder();
            if (!string.IsNullOrWhiteSpace(advancedConfig.DevName))
            {
                flagsSb.AppendLine($"dev_name = \"{EscapeTomlString(advancedConfig.DevName)}\"");
            }
            if (advancedConfig.Mtu.HasValue && advancedConfig.Mtu.Value > 0)
            {
                flagsSb.AppendLine($"mtu = {advancedConfig.Mtu.Value}");
            }
            if (advancedConfig.EnableIpv6.HasValue)
            {
                flagsSb.AppendLine($"enable_ipv6 = {(advancedConfig.EnableIpv6.Value ? "true" : "false")}");
            }
            if (advancedConfig.LatencyFirst.HasValue)
            {
                flagsSb.AppendLine($"latency_first = {(advancedConfig.LatencyFirst.Value ? "true" : "false")}");
            }
            if (advancedConfig.BindDevice.HasValue)
            {
                flagsSb.AppendLine($"bind_device = {(advancedConfig.BindDevice.Value ? "true" : "false")}");
            }
            if (!string.IsNullOrWhiteSpace(advancedConfig.DefaultProtocol))
            {
                flagsSb.AppendLine($"default_protocol = \"{EscapeTomlString(advancedConfig.DefaultProtocol.ToLowerInvariant())}\"");
            }

            // P2P 连接模式（互斥设置）
            var p2p = advancedConfig.P2pMode?.Trim().ToLowerInvariant();
            if (p2p == "p2p_only") flagsSb.AppendLine("p2p_only = true");
            else if (p2p == "disable_p2p" || p2p == "relay_only") flagsSb.AppendLine("disable_p2p = true");
            else if (p2p == "lazy_p2p") flagsSb.AppendLine("lazy_p2p = true");
            else if (p2p == "need_p2p") flagsSb.AppendLine("need_p2p = true");

            // UPnP
            if (advancedConfig.EnableUpnp.HasValue)
            {
                flagsSb.AppendLine($"disable_upnp = {(!advancedConfig.EnableUpnp.Value ? "true" : "false")}");
            }

            // 打洞诊断微调
            if (advancedConfig.EnableTcpHolePunching.HasValue)
            {
                flagsSb.AppendLine($"disable_tcp_hole_punching = {(!advancedConfig.EnableTcpHolePunching.Value ? "true" : "false")}");
            }
            if (advancedConfig.EnableUdpHolePunching.HasValue)
            {
                flagsSb.AppendLine($"disable_udp_hole_punching = {(!advancedConfig.EnableUdpHolePunching.Value ? "true" : "false")}");
            }
            if (advancedConfig.EnableSymHolePunching.HasValue)
            {
                flagsSb.AppendLine($"disable_sym_hole_punching = {(!advancedConfig.EnableSymHolePunching.Value ? "true" : "false")}");
            }

            var flagsContent = flagsSb.ToString().Trim();
            if (!string.IsNullOrEmpty(flagsContent))
            {
                sb.AppendLine("[flags]");
                sb.AppendLine(flagsContent);
                sb.AppendLine();
            }
        }

        // 4. 表数组：[[peer]]
        if (peers.Count > 0)
        {
            foreach (var p in peers)
            {
                sb.AppendLine("[[peer]]");
                sb.AppendLine($"uri = \"{EscapeTomlString(p)}\"");
                sb.AppendLine();
            }
        }

        // 5. 表数组：[[proxy_network]] 支持 cidr 与 mapped_cidr 网段映射
        if (proxyRules.Count > 0)
        {
            foreach (var pr in proxyRules)
            {
                if (string.IsNullOrWhiteSpace(pr.Cidr)) continue;

                if (!string.IsNullOrWhiteSpace(pr.MappedCidr))
                {
                    if (!ValidateCidr(pr.Cidr, out var srcPrefix, out var srcErr))
                        throw new ArgumentException($"子网代理源网段格式无效 ({pr.Cidr}): {srcErr}");
                    if (!ValidateCidr(pr.MappedCidr, out var dstPrefix, out var dstErr))
                        throw new ArgumentException($"子网映射目标网段格式无效 ({pr.MappedCidr}): {dstErr}");
                    if (srcPrefix != dstPrefix)
                        throw new ArgumentException($"子网映射前缀大小必须匹配: 源网段 /{srcPrefix} 与映射网段 /{dstPrefix} 掩码前缀长度必须一致");
                    if (string.Equals(pr.Cidr, pr.MappedCidr, StringComparison.OrdinalIgnoreCase))
                        throw new ArgumentException($"子网映射源网段与映射网段不能与原始 CIDR 完全相同 ({pr.Cidr})");
                }

                sb.AppendLine("[[proxy_network]]");
                sb.AppendLine($"cidr = \"{EscapeTomlString(pr.Cidr)}\"");
                if (!string.IsNullOrWhiteSpace(pr.MappedCidr))
                {
                    sb.AppendLine($"mapped_cidr = \"{EscapeTomlString(pr.MappedCidr)}\"");
                }
                sb.AppendLine();
            }
        }

        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    public static bool ValidateConfig(string toml, out string? error)
    {
        return ValidateConfig(toml, coreBinaryPath: null, out error);
    }

    public static bool ValidateConfig(string toml, string? coreBinaryPath, out string? error)
    {
        if (string.IsNullOrWhiteSpace(toml))
        {
            error = "配置内容不能为空";
            return false;
        }

        // 1. 结构与顶层字段合法性检查（防表作用域污染）
        var lines = toml.Split('\n');
        var hasInstName = false;
        var seenTable = false;

        foreach (var rawLine in lines)
        {
            var line = rawLine.Trim();
            if (line.StartsWith('#') || string.IsNullOrWhiteSpace(line)) continue;

            if (line.StartsWith('['))
            {
                seenTable = true;
                continue;
            }

            if (!seenTable)
            {
                if (Regex.IsMatch(line, @"^(inst_name|instance_name)\s*="))
                {
                    hasInstName = true;
                }
            }
            else
            {
                // 如果已经在子表之后，检查是否有应该放在顶层的关键字段错误放置在子表中
                if (Regex.IsMatch(line, @"^(inst_name|instance_name)\s*="))
                {
                    error = "实例名称 (inst_name/instance_name) 必须位于所有 TOML 表 ([table]) 之前作为顶层配置";
                    return false;
                }
            }
        }

        if (!hasInstName)
        {
            error = "缺少必需的顶层 inst_name 或 instance_name 字段";
            return false;
        }

        // 2. 子网映射前缀匹配与有效性校验
        var proxySections = Regex.Matches(toml, @"\[\[proxy_network\]\](?<content>[\s\S]*?)(?=(\[\[|\z))");
        foreach (Match m in proxySections)
        {
            var content = m.Groups["content"].Value;
            var cidrMatch = Regex.Match(content, @"(?m)^\s*cidr\s*=\s*""([^""]+)""");
            var mappedMatch = Regex.Match(content, @"(?m)^\s*mapped_cidr\s*=\s*""([^""]+)""");

            if (cidrMatch.Success && mappedMatch.Success)
            {
                var src = cidrMatch.Groups[1].Value.Trim();
                var mapped = mappedMatch.Groups[1].Value.Trim();
                if (!ValidateCidr(src, out var srcPrefix, out var srcErr))
                {
                    error = $"子网代理源网段格式无效 ({src}): {srcErr}";
                    return false;
                }
                if (!ValidateCidr(mapped, out var mappedPrefix, out var mappedErr))
                {
                    error = $"子网映射目标网段格式无效 ({mapped}): {mappedErr}";
                    return false;
                }
                if (srcPrefix != mappedPrefix)
                {
                    error = $"子网映射前缀大小必须匹配: 源网段 /{srcPrefix} 与映射网段 /{mappedPrefix} 不一致";
                    return false;
                }
                if (string.Equals(src, mapped, StringComparison.OrdinalIgnoreCase))
                {
                    error = $"子网映射源网段与映射网段不能相同 ({src})";
                    return false;
                }
            }
            else if (cidrMatch.Success)
            {
                var src = cidrMatch.Groups[1].Value.Trim();
                if (!ValidateCidr(src, out _, out var srcErr))
                {
                    error = $"子网代理网段格式无效 ({src}): {srcErr}";
                    return false;
                }
            }
        }

        // 3. 如果提供了 coreBinaryPath 且文件存在，调用官方 --check-config 并进行错误脱敏
        if (!string.IsNullOrWhiteSpace(coreBinaryPath) && File.Exists(coreBinaryPath))
        {
            var tempFile = Path.Combine(Path.GetTempPath(), $"et_check_{Guid.NewGuid():N}.toml");
            try
            {
                File.WriteAllText(tempFile, toml, Encoding.UTF8);
                using var proc = new Process
                {
                    StartInfo = new ProcessStartInfo
                    {
                        FileName = coreBinaryPath,
                        Arguments = $"--check-config -c \"{tempFile}\"",
                        RedirectStandardOutput = true,
                        RedirectStandardError = true,
                        UseShellExecute = false,
                        CreateNoWindow = true
                    }
                };

                proc.Start();
                var stderr = proc.StandardError.ReadToEnd();
                var stdout = proc.StandardOutput.ReadToEnd();
                if (!proc.WaitForExit(3000))
                {
                    try { proc.Kill(); } catch { }
                }

                if (proc.ExitCode != 0)
                {
                    var rawErr = !string.IsNullOrWhiteSpace(stderr) ? stderr : stdout;
                    error = $"EasyTier 内核校验未通过: {SanitizeErrorMessage(rawErr)}";
                    return false;
                }
            }
            catch (Exception ex)
            {
                error = $"执行内核配置校验异常: {SanitizeErrorMessage(ex.Message)}";
                return false;
            }
            finally
            {
                try { if (File.Exists(tempFile)) File.Delete(tempFile); } catch { }
            }

            error = null;
            return true;
        }

        // 4. 若为 Native FFI 动态库就绪环境
        if (EasyTierNativeMethods.ProbeLibrary(out _))
        {
            try
            {
                var ret = EasyTierNativeMethods.parse_config(toml);
                if (ret != 0)
                {
                    error = SanitizeErrorMessage(EasyTierNativeMethods.GetLastErrorMessage());
                    return false;
                }
                error = null;
                return true;
            }
            catch (Exception ex)
            {
                error = $"调用 parse_config 发生异常: {SanitizeErrorMessage(ex.Message)}";
                return false;
            }
        }

        error = null;
        return true;
    }

    public static string SanitizeErrorMessage(string? error)
    {
        if (string.IsNullOrWhiteSpace(error)) return "未知错误";

        // 剥离临时文件路径
        var sanitized = Regex.Replace(error, @"(?i)[a-z]:\\[^""\r\n]+\.toml", "[配置文件]");
        sanitized = Regex.Replace(sanitized, @"/tmp/[^""\r\n]+\.toml", "[配置文件]");
        sanitized = Regex.Replace(sanitized, @"(?i)[a-z]:\\[^""\r\n]+\.tmp", "[临时文件]");
        sanitized = Regex.Replace(sanitized, @"/tmp/[^""\r\n]+\.tmp", "[临时文件]");

        // 脱敏网络密钥
        sanitized = Regex.Replace(sanitized, @"(network_secret\s*=\s*""[^""]+"")", "network_secret = \"******\"");

        return sanitized.Trim();
    }

    public static bool ValidateCidr(string cidr, out int prefix, out string? error)
    {
        prefix = 0;
        error = null;
        var parts = cidr.Split('/');
        if (parts.Length != 2)
        {
            error = "需包含掩码前缀 (如 192.168.1.0/24)";
            return false;
        }
        if (!IPAddress.TryParse(parts[0], out var ip) || ip.AddressFamily != AddressFamily.InterNetwork)
        {
            error = "需为有效 IPv4 地址";
            return false;
        }
        if (!int.TryParse(parts[1], out prefix) || prefix < 0 || prefix > 32)
        {
            error = "掩码位数必须在 0 到 32 之间";
            return false;
        }
        return true;
    }

    public static List<EasyTierProxyNetworkItem> ResolveProxyRules(
        List<EasyTierProxyNetworkItem>? rules,
        List<string>? networks)
    {
        if (rules != null && rules.Count > 0) return rules;
        if (networks == null || networks.Count == 0) return [];

        var list = new List<EasyTierProxyNetworkItem>();
        foreach (var net in networks)
        {
            if (string.IsNullOrWhiteSpace(net)) continue;
            var trimmed = net.Trim();
            if (trimmed.Contains("=>"))
            {
                var parts = trimmed.Split("=>", StringSplitOptions.TrimEntries);
                list.Add(new EasyTierProxyNetworkItem(parts[0], parts.Length > 1 ? parts[1] : null));
            }
            else if (trimmed.Contains("->"))
            {
                var parts = trimmed.Split("->", StringSplitOptions.TrimEntries);
                list.Add(new EasyTierProxyNetworkItem(parts[0], parts.Length > 1 ? parts[1] : null));
            }
            else
            {
                list.Add(new EasyTierProxyNetworkItem(trimmed, null));
            }
        }
        return list;
    }

    public static List<EasyTierProxyNetworkItem> DeserializeProxyRules(string? rulesJson, string? networksJson)
    {
        if (!string.IsNullOrWhiteSpace(rulesJson))
        {
            try
            {
                var list = JsonSerializer.Deserialize(rulesJson, EasyTierJsonContext.Default.ListEasyTierProxyNetworkItem);
                if (list != null && list.Count > 0) return list;
            }
            catch { }
        }

        var strings = DeserializeList(networksJson);
        return ResolveProxyRules(null, strings);
    }

    public static EasyTierAdvancedConfig? DeserializeAdvancedConfig(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return null;
        try
        {
            return JsonSerializer.Deserialize(json, EasyTierJsonContext.Default.EasyTierAdvancedConfig);
        }
        catch
        {
            return null;
        }
    }

    public static List<string> DeserializeList(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return [];
        try
        {
            return JsonSerializer.Deserialize(json, EasyTierJsonContext.Default.ListString) ?? [];
        }
        catch
        {
            return [];
        }
    }

    private static List<string> NormalizeListeners(List<string> listeners)
    {
        var result = new List<string>();
        foreach (var item in listeners)
        {
            var trimmed = item.Trim();
            if (string.IsNullOrEmpty(trimmed)) continue;

            // 纯端口号（例如 "11010"）自动补充 tcp、udp、wg 的 IPv4 与 IPv6 全套监听
            if (int.TryParse(trimmed, out var port) && port > 0 && port <= 65535)
            {
                result.Add($"tcp://0.0.0.0:{port}");
                result.Add($"udp://0.0.0.0:{port}");
                result.Add($"wg://0.0.0.0:{port + 1}");
                result.Add($"tcp://[::]:{port}");
                result.Add($"udp://[::]:{port}");
                result.Add($"wg://[::]:{port + 1}");
            }
            // 缺少 scheme 的 host:port（例如 "0.0.0.0:11010" 或 ":11010"）
            else if (trimmed.Contains(':') && !trimmed.Contains("://"))
            {
                var hostPort = trimmed.TrimStart(':');
                if (!hostPort.Contains(':')) hostPort = $"0.0.0.0:{hostPort}";
                result.Add($"tcp://{hostPort}");
                result.Add($"udp://{hostPort}");
            }
            // wg:// 前缀处理（默认端口 11011）
            else if (trimmed.StartsWith("wg://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[5..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("wg://0.0.0.0:11011");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("wg://[::]:11011");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"wg://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11011");
                else result.Add(trimmed);
            }
            // udp:// 前缀处理（默认端口 11010）
            else if (trimmed.StartsWith("udp://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[6..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("udp://0.0.0.0:11010");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("udp://[::]:11010");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"udp://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11010");
                else result.Add(trimmed);
            }
            // tcp:// 前缀处理（默认端口 11010）
            else if (trimmed.StartsWith("tcp://", StringComparison.OrdinalIgnoreCase))
            {
                var rest = trimmed[6..];
                if (string.Equals(rest, "0.0.0.0", StringComparison.OrdinalIgnoreCase)) result.Add("tcp://0.0.0.0:11010");
                else if (string.Equals(rest, "[::]", StringComparison.OrdinalIgnoreCase) || string.Equals(rest, "::", StringComparison.OrdinalIgnoreCase)) result.Add("tcp://[::]:11010");
                else if (int.TryParse(rest.TrimStart(':'), out var p)) result.Add($"tcp://0.0.0.0:{p}");
                else if (!rest.Contains(':')) result.Add($"{trimmed}:11010");
                else result.Add(trimmed);
            }
            else
            {
                result.Add(trimmed);
            }
        }
        return result;
    }

    private static string EscapeTomlString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
